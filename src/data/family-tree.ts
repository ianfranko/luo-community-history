export function getMember(id: string): FamilyMember | undefined {
  return familyMembers.find((m) => m.id === id)
}

export function getMemberBySlug(slug: string): FamilyMember | undefined {
  return familyMembers.find((m) => m.slug === slug)
}

export function getChildren(id: string): FamilyMember[] {
  const member = getMember(id)
  if (!member) return []
  return member.childrenIds
    .map((childId) => getMember(childId))
    .filter((m): m is FamilyMember => !!m)
}

export function getParents(id: string): FamilyMember[] {
  const member = getMember(id)
  if (!member) return []
  return member.parentIds
    .map((pid) => getMember(pid))
    .filter((m): m is FamilyMember => !!m)
}

